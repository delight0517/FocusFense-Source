  static String t(Locale locale, String key) {
    final String lang =
        supportedLocales.any(
          (Locale e) => e.languageCode == locale.languageCode,
        )
        ? locale.languageCode
        : 'en';
    return _dict[lang]?[key] ?? _dict['en']![key] ?? key;
  }

  static String languageName(String code) {
    switch (code) {
      case 'en':
        return 'English';
      case 'ja':
        return '日本語';
      case 'zh':
        return '中文';
      case 'ko':
        return '한국어';
      case 'he':
        return 'עברית';
      case 'ar':
        return 'العربية';
      default:
        return code;
    }
  }
